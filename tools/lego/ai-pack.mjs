function adrIndex() {
  const dir = join(REPO_ROOT, 'docs', 'architecture', 'adr');
  let rows = [];
  if (existsSync(dir)) {
    rows = readdirSync(dir).filter((file) => file.endsWith('.md')).sort().map((file) => {
      const first = normalizeEol(readFileSync(join(dir, file), 'utf8')).split('\n').find((line) => line.startsWith('# ')) ?? file;
      return `| [\`${file.replace('.md', '')}\`](../docs/architecture/adr/${file}) | ${first.replace(/^#\s*/, '')} |`;
    });
  }
  return `${BANNER}
# ADR index

Architecture decisions. Each records the decision, the reason, the alternatives considered, the consequences, and the date/version.

| ADR | Decision |
| --- | --- |
${rows.join('\n') || '| _none_ | |'}

New ADRs go in \`docs/architecture/adr/\` and this index regenerates.
`;
}

